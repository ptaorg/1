// ========== Mobile menu toggle ==========
(function() {
  const toggle = document.querySelector('.mobile-toggle');
  const menu = document.getElementById('mobile-menu');
  if (!toggle || !menu) return;
  toggle.addEventListener('click', () => {
    const open = menu.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
  });
})();

// ========== Dropdown nav (click for mobile-friendly) ==========
(function() {
  const triggers = document.querySelectorAll('.nav-trigger');
  triggers.forEach(t => {
    t.addEventListener('click', (e) => {
      e.preventDefault();
      const group = t.closest('.nav-group');
      const isOpen = group.classList.contains('is-open');
      // Close all
      document.querySelectorAll('.nav-group.is-open').forEach(g => g.classList.remove('is-open'));
      if (!isOpen) {
        group.classList.add('is-open');
        t.setAttribute('aria-expanded', 'true');
      } else {
        t.setAttribute('aria-expanded', 'false');
      }
    });
  });
  document.addEventListener('click', (e) => {
    if (!e.target.closest('.nav-group')) {
      document.querySelectorAll('.nav-group.is-open').forEach(g => g.classList.remove('is-open'));
    }
  });
})();

// ========== Generic tab switcher ==========
(function() {
  document.querySelectorAll('[data-tabs]').forEach(container => {
    const buttons = container.querySelectorAll('.tab-btn');
    const panels = container.querySelectorAll('.tab-panel');
    buttons.forEach(btn => {
      btn.addEventListener('click', () => {
        const target = btn.dataset.tab;
        buttons.forEach(b => b.classList.remove('is-active'));
        panels.forEach(p => p.classList.remove('is-active'));
        btn.classList.add('is-active');
        const panel = container.querySelector(`#tab-${target}`);
        if (panel) panel.classList.add('is-active');
        if (history.replaceState) history.replaceState(null, '', '#' + target);
      });
    });
    const hash = location.hash.replace('#', '');
    if (hash) {
      const btn = container.querySelector(`.tab-btn[data-tab="${hash}"]`);
      if (btn) btn.click();
    }
  });
})();
